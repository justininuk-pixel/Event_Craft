/** Whether an experience (by raw id or its alias target) handles the creator's message itself. */
export function experienceHandlesOwnText(experienceId: string | undefined): boolean {
  if (!experienceId) return true;
  const resolved = EXPERIENCE_ALIASES[experienceId] ?? experienceId;
  return !NON_TEXT_EXPERIENCE_IDS.has(resolved) && !NON_TEXT_EXPERIENCE_IDS.has(experienceId);
}

/** Resolve a theme's experienceId to a mounted component, honouring aliases. */
export function resolveExperienceComponent(
  experienceId: string | undefined,
): ComponentType<ExperienceViewProps> | undefined {
  if (!experienceId) return undefined;
  return (
    EXPERIENCE_COMPONENTS[experienceId] ??
    EXPERIENCE_COMPONENTS[EXPERIENCE_ALIASES[experienceId]]
  );
}

/** Whether a theme's experienceId maps to a real experience mini-app. */
export function hasExperience(experienceId: string | undefined): boolean {
  return resolveExperienceComponent(experienceId) !== undefined;
}

/**
 * ExperienceHost applies the editable style layer (palette + fonts + background)
 * and then dispatches to the correct experience mini-app. The STRUCTURE lives in
 * the child component; STYLE is everything applied here.
 */
export function ExperienceHost({
  theme,
  config,
  mode,
  contributions,
  onInteractionComplete,
}: ExperienceHostProps) {
  const palette = config.palette || theme.visual.palette;
  const headingFont = config.fontHeading || theme.visual.fonts.heading;
  const bodyFont = config.fontBody || theme.visual.fonts.body;
  const tone = config.emotionalTone ?? 50;

  // Track whether the experience has been completed so timed elements
  // ("show only at the end") can unlock in the viewer.
  const [completed, setCompleted] = useState(false);
  const celebratedRef = useRef(false);
  const handleComplete = useCallback(() => {
    setCompleted(true);
    if (!celebratedRef.current) {
      celebratedRef.current = true;
      // Central end-of-experience celebration, most of the ~500 plan-theme experiences
      // never fired their own confetti, so cards ended flat with no celebration.
      fireConfetti(
        [palette.primary, palette.accent, palette.secondary].filter(
          (c): c is string => typeof c === "string",
        ),
        toneIntensity(tone),
      );
    }
    onInteractionComplete?.();
  }, [onInteractionComplete, palette, tone]);

  useEffect(() => {
    loadFont(headingFont).catch(() => {});
    loadFont(bodyFont).catch(() => {});
  }, [headingFont, bodyFont]);

  // CSS custom properties consumed by the experiences. Cast through Record so
  // the `--exp-*` keys are accepted by React.CSSProperties under strict TS.
  const styleVars = {
    "--exp-primary": palette.primary,
    "--exp-secondary": palette.secondary,
    "--exp-accent": palette.accent,
    "--exp-text": palette.text,
    "--exp-text-secondary": palette.textSecondary,
    "--exp-font-heading": `'${headingFont}', Georgia, serif`,
    "--exp-font-body": `'${bodyFont}', system-ui, sans-serif`,
    "--exp-tone": String(tone / 100),
    background: backgroundCss(palette),
    color: palette.text,
    fontFamily: `'${bodyFont}', system-ui, sans-serif`,
  } as React.CSSProperties;

  const viewProps: ExperienceViewProps = {
    theme,
    config,
    mode,
    palette,
    headingFont,
    bodyFont,
    tone,
    contributions,
    onComplete: handleComplete,
  };

  // Direct index access (not a function call) so the React-compiler lint doesn't
  // treat this as "creating a component during render". Mirrors resolveExperienceComponent.
  const expId = theme.experienceId ?? "";
  const Experience =
    EXPERIENCE_COMPONENTS[expId] ?? EXPERIENCE_COMPONENTS[EXPERIENCE_ALIASES[expId]];

  return (
    <div
      className="absolute inset-0 w-full h-full overflow-hidden"
      style={styleVars}
      data-experience={theme.experienceId}
    >
      {Experience && <Experience {...viewProps} />}

      {/* Stickers / elements added in the editor. Experiences previously rendered none of these,
          so anything the user placed was invisible on the card. */}
      <StickerLayer stickers={config.stickers} mode={mode} revealed={completed} />

      {/* Surface the creator's message on experiences that don't render it themselves (games,
          generative/AI pieces, data-viz). Hidden in the tiny gallery preview to avoid clutter. */}
      {mode !== "gallery-mini" && !experienceHandlesOwnText(theme.experienceId) && (
        <MessageAffordance theme={theme} config={config} palette={palette} />
      )}

      {config.dynamicTime && <DynamicTimeOverlay recipient={config.recipient} />}
    </div>
  );
}

export default ExperienceHost;

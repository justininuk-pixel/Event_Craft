export function backgroundCss(palette: ThemePalette): string {
  const bg = palette.background;
  if (Array.isArray(bg)) {
    if (bg.length === 1) return bg[0];
    return `linear-gradient(160deg, ${bg.join(", ")})`;
  }
  return bg;
}

